#!/usr/bin/env python3
"""Phase 4: held-out comparison of A1-A3, R1 (selected, final) and the V2 candidates
(PROTOCOL.md Section 4).  Setting A = full original grasp distribution (main), Setting B =
Phase 1 nominal grasp and robust subset.  Seeds 6201+6202 (nominal), 6201 (presets).
Bootstrap 95% CIs over environments; pre-registered thresholds.  Writes
results/phase4.{json,md}, figures/p4_*.png.

    python experiments/grasp_rotation_v2/scripts/compare_v2.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from compare_p1 import METRICS, metrics  # noqa: E402

E = Path("experiments/grasp_rotation_v2")
A_POL = ("A1", "A2", "A3")
CANDS = ("P0", "C5")
PRESETS = ("heavy_slippery", "high_delay", "obs_noise_x3")


def load(cond, pol, preset="nominal", seeds=(6201, 6202)):
  fs = [E / "data" / f"ho_{cond}_{pol}_{preset}_s{s}.npz" for s in seeds]
  if not all(f.exists() for f in fs):
    return None
  parts = [metrics(f) for f in fs]
  return {k: np.concatenate([x[k] for x in parts]) for k in parts[0]}


def diff_ci(cand, refs, metric, n=2000):
  """cand - mean(refs) for a metric, CI by resampling environments within each policy."""
  rng = np.random.default_rng(1)
  pt = cand[metric].mean() - np.mean([r[metric].mean() for r in refs])
  bs = []
  for _ in range(n):
    c = cand[metric][rng.integers(0, len(cand[metric]), len(cand[metric]))].mean()
    r = np.mean([x[metric][rng.integers(0, len(x[metric]), len(x[metric]))].mean() for x in refs])
    bs.append(c - r)
  return float(pt), [float(np.quantile(bs, 0.025)), float(np.quantile(bs, 0.975))]


def table(cond, preset, seeds, pols):
  out = {}
  for p in pols:
    d = load(cond, p, preset, seeds)
    if d is not None:
      out[p] = d
  return out


def main():
  pols = list(A_POL) + ["R1", "R1final"] + list(CANDS) + [c + "final" for c in CANDS]
  res = {"settingA": {}, "settingB": {}, "thresholds": {}}
  A = table("A", "nominal", (6201, 6202), pols)
  res["settingA"]["nominal"] = {p: {m: float(d[m].mean()) for m in METRICS} for p, d in A.items()}
  if all(p in A for p in A_POL):
    res["settingA"]["nominal"]["A_mean"] = {m: float(np.mean([A[p][m].mean() for p in A_POL])) for m in METRICS}
  for c in CANDS:
    if c in A and all(p in A for p in A_POL) and "R1" in A:
      res["settingA"].setdefault("diffs", {})[c] = {
        "vs_A_mean": {m: dict(zip(("diff", "ci95"), diff_ci(A[c], [A[p] for p in A_POL], m))) for m in METRICS},
        "vs_R1": {m: dict(zip(("diff", "ci95"), diff_ci(A[c], [A["R1"]], m))) for m in METRICS}}
  for pr in PRESETS:
    T = table("A", pr, (6201,), pols)
    res["settingA"][pr] = {p: {m: float(d[m].mean()) for m in METRICS} for p, d in T.items()}
    if all(p in T for p in A_POL):
      res["settingA"][pr]["A_mean"] = {m: float(np.mean([T[p][m].mean() for p in A_POL])) for m in METRICS}
  am = res["settingA"]["nominal"].get("A_mean")
  r1 = res["settingA"]["nominal"].get("R1")
  for c in CANDS:
    v = res["settingA"]["nominal"].get(c)
    if v is None or am is None or r1 is None:
      continue
    th = {"1_yaw_ge_A": v["yaw30"] >= am["yaw30"],
          "2_turns_ge_1.05A_and_1.10R1": v["turns30"] >= 1.05 * am["turns30"] and v["turns30"] >= 1.10 * r1["turns30"],
          "3_fail_le_midpoint": v["fail30"] <= (am["fail30"] + r1["fail30"]) / 2,
          "4_held60_ge_A": v["held60"] >= am["held60"]}
    rob = {}
    for pr in PRESETS:
      t = res["settingA"].get(pr, {})
      if c in t and "A_mean" in t:
        rob[pr] = t[c]["turns30"] >= 0.9 * t["A_mean"]["turns30"]
    th["5_robustness"] = bool(rob) and all(rob.values()) and len(rob) == len(PRESETS)
    th["5_detail"] = rob
    th["promising"] = all(th[k] for k in ("1_yaw_ge_A", "2_turns_ge_1.05A_and_1.10R1", "3_fail_le_midpoint", "4_held60_ge_A", "5_robustness"))
    res["thresholds"][c] = th
  for cond, nm in (("B", "nominal_grasp"), ("C", "robust_subset")):
    T = table(cond, "nominal", (6201, 6202), pols)
    res["settingB"][nm] = {p: {m: float(d[m].mean()) for m in METRICS} for p, d in T.items()}
    if all(p in T for p in A_POL):
      res["settingB"][nm]["A_mean"] = {m: float(np.mean([T[p][m].mean() for p in A_POL])) for m in METRICS}
  N = table("N", "nominal", (6201,), pols)
  res["supplementary_no_pose_rule"] = {p: {"turns30": float(d["turns30"].mean()), "turns60": float(d["turns60"].mean()),
                                           "real_drop60": float(d["fail60"].mean()), "yaw60": float(d["yaw60"].mean())} for p, d in N.items()}
  (E / "results" / "phase4.json").write_text(json.dumps(res, indent=1, default=bool))
  md(res)
  figures(res)


def md(res):
  L = ["# Phase 4 held-out comparison (generated by scripts/compare_v2.py)", ""]
  hdr = "| policy | 30-s turns | 30-s failure | 30-s survival | yaw rate held | 60-s turns | P(held 60 s) |\n|---|---|---|---|---|---|---|"
  for title, block in (("Setting A (main): full original grasp distribution, nominal, seeds 6201+6202", res["settingA"]["nominal"]),
                       *[(f"Setting A, {pr}, seed 6201", res["settingA"].get(pr, {})) for pr in PRESETS],
                       ("Setting B: nominal grasp 49, seeds 6201+6202", res["settingB"].get("nominal_grasp", {})),
                       ("Setting B: robust subset (10 grasps), seeds 6201+6202", res["settingB"].get("robust_subset", {}))):
    L += [f"## {title}", "", hdr]
    for p, r in block.items():
      L.append(f"| {p} | {r['turns30']:.3f} | {r['fail30']:.3f} | {r['surv30']:.1f} | {r['yaw30']:.3f} | {r['turns60']:.3f} | {r['held60']:.3f} |")
    L.append("")
  for c, d in res["settingA"].get("diffs", {}).items():
    L.append(f"**{c}** vs A mean: " + "; ".join(f"{m} {d['vs_A_mean'][m]['diff']:+.3f} [{d['vs_A_mean'][m]['ci95'][0]:+.3f}, {d['vs_A_mean'][m]['ci95'][1]:+.3f}]" for m in METRICS))
    L.append("")
    L.append(f"**{c}** vs R1: " + "; ".join(f"{m} {d['vs_R1'][m]['diff']:+.3f} [{d['vs_R1'][m]['ci95'][0]:+.3f}, {d['vs_R1'][m]['ci95'][1]:+.3f}]" for m in METRICS))
    L.append("")
  L += ["## Supplementary (not pre-registered): pose-deviation rule switched off, full distribution, seed 6201", "",
        "Only cube_fell / cube_too_fast end an episode; real_drop60 = share dropped or thrown within 60 s.", "",
        "| policy | 30-s turns | 60-s turns | real drop 60 s | yaw rate held |", "|---|---|---|---|---|"]
  for p, r in res.get("supplementary_no_pose_rule", {}).items():
    L.append(f"| {p} | {r['turns30']:.3f} | {r['turns60']:.3f} | {r['real_drop60']:.3f} | {r['yaw60']:.3f} |")
  L.append("")
  L += ["## Pre-registered thresholds", "", "```", json.dumps(res["thresholds"], indent=1, default=bool), "```"]
  (E / "results" / "phase4.md").write_text("\n".join(L) + "\n")
  print("\n".join(L))


def figures(res):
  import matplotlib

  matplotlib.use("Agg")
  import matplotlib.pyplot as plt

  cur = {}
  for r, p in (("A1", "../hwlimit_ac/results/curves/A1.json"), ("A2", "../hwlimit_ac/results/curves/A2.json"),
               ("A3", "../hwlimit_ac/results/curves/A3.json"), ("R1", "../retention_v1/results/curves/R1.json"),
               ("P0", "results/curves/P0_1.json"), ("C5", "results/curves/C5_1.json")):
    f = E / p
    if f.exists():
      pts = json.loads(f.read_text())["points"]
      its = sorted(int(k) for k in pts)
      cur[r] = (its, [pts[str(i)]["turns"]["mean"] for i in its], [pts[str(i)]["failure"]["mean"] for i in its],
                [pts[str(i)]["mean_yaw_rate"]["mean"] for i in its])
  sty = {"A1": ("#9a9a9a", "-"), "A2": ("#9a9a9a", "--"), "A3": ("#9a9a9a", ":"), "R1": ("#3b6fb6", "-"), "P0": ("#e4572e", "-"), "C5": ("#2a9d8f", "-")}
  fig, ax = plt.subplots(1, 3, figsize=(16, 4.3))
  for r, (its, v, f, y) in cur.items():
    c, ls = sty[r]
    for a, s in zip(ax, (v, f, y)):
      a.plot(its, s, color=c, ls=ls, lw=2 if r in ("P0", "C5", "R1") else 1.2, label=r)
  for a, t in zip(ax, ("validation turns (30 s)", "validation failure rate", "validation yaw rate while held (rad/s)")):
    a.set(title=t, xlabel="PPO update")
  ax[0].legend()
  fig.suptitle("Validation curves (seed 7001, nominal, 1024 environments): one training seed per V2 candidate")
  fig.tight_layout()
  fig.savefig(E / "figures" / "p4_learning_curves.png", dpi=130)
  plt.close(fig)
  blk = res["settingA"]["nominal"]
  order = [p for p in ("A1", "A2", "A3", "R1", "R1final", "P0", "P0final", "C5", "C5final") if p in blk]
  fig, ax = plt.subplots(1, 4, figsize=(17, 4))
  for a, m, t in zip(ax, ("turns30", "fail30", "yaw30", "held60"), ("30-s turns", "30-s failure rate", "yaw rate while held", "P(held 60 s)")):
    cols = ["#9a9a9a" if p.startswith("A") else "#3b6fb6" if p.startswith("R1") else "#e4572e" if p.startswith("P0") else "#2a9d8f" for p in order]
    a.bar(range(len(order)), [blk[p][m] for p in order], color=cols)
    a.set_xticks(range(len(order)), order, rotation=30)
    a.set_title(t)
  fig.suptitle("Setting A (full grasp distribution), held-out seeds 6201+6202")
  fig.tight_layout()
  fig.savefig(E / "figures" / "p4_settingA.png", dpi=130)
  plt.close(fig)


if __name__ == "__main__":
  main()
