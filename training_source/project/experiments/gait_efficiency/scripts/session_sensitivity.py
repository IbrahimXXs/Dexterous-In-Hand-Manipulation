#!/usr/bin/env python3
"""Gait efficiency, sensitivity (EXPLORATORY, POST HOC): seed vs session, and the short-window 24 Nov trial 13.

Most C5 seed 1 runs are from 20 Nov and most C5 seed 3 runs from 24-25 Nov, so the C5s1/C5s3 difference in quarter
turns per finger cycle could be a session effect.  On 24 Nov both seeds ran.  This script recomputes, with the
unchanged held-window counter (real_hand.py ``per_run`` with window "held", runs held >= 20 s, which calls
gait.py ``count_cycles``), quarter turns per cycle per run, and checks every value against
results/real_hand.json (variant "held", per_run).  It also reports C5s3 pooled without 24 Nov trial 13
(held exactly 20 s; 3.1 cycles in a 17-s window, so the counter undercounts and the run gives an implausible
value).  Nothing else is regenerated.

    python experiments/gait_efficiency/scripts/session_sensitivity.py      (from training_source/project)
Writes results/session_sensitivity.json and results/session_sensitivity.md.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import numpy as np

E = Path(__file__).resolve().parents[1]
_spec = importlib.util.spec_from_file_location("gait_real_hand", E / "scripts" / "real_hand.py")
RH = importlib.util.module_from_spec(_spec)
sys.modules["gait_real_hand"] = RH
_spec.loader.exec_module(RH)

NBOOT = 10000
EXCLUDE = ("24 Nov", 13)


def pooled(rows: list[dict], rng: np.random.Generator) -> dict:
  qt = np.array([r["qturns"] for r in rows])
  cy = np.array([r["cycles"] for r in rows])
  bs = np.empty(NBOOT)
  for i in range(NBOOT):
    j = rng.integers(0, len(rows), len(rows))
    bs[i] = qt[j].sum() / cy[j].sum()
  return {"n_runs": len(rows), "runs": [f"{r['session']} t{r['trial']}" for r in rows],
          "qturns_total": float(qt.sum()), "cycles_total": float(cy.sum()),
          "qturns_per_cycle": float(qt.sum() / cy.sum()),
          "qturns_per_cycle_ci95": [float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))]}


def main() -> None:
  rng = np.random.default_rng(20261127)
  rows = RH.per_run(RH.load_runs(), min_s=20.0, basis="held_s", window="held")
  ref = {(r["session"], r["trial"]): r for r in json.loads((E / "results" / "real_hand.json").read_text())["variants"]["held"]["per_run"]}
  for r in rows:  # the recomputation must equal the committed held-variant rows
    k = (r["session"], r["trial"])
    assert k in ref and abs(ref[k]["cycles"] - r["cycles"]) < 1e-9 and ref[k]["qturns"] == r["qturns"], k
  c5 = [r for r in rows if r["policy"] in ("C5s1", "C5s3") and r["status"] == "ok"]
  per = [{"session": r["session"], "trial": r["trial"], "policy": r["policy"], "held_s": r["held_s"], "window_s": r["window_s"],
          "qturns": r["qturns"], "cycles": r["cycles"], "qturns_per_cycle": r["qturns"] / r["cycles"], "rhythm_hz": r["rhythm_hz"]}
         for r in c5]
  out = {"label": "EXPLORATORY, POST HOC sensitivity; held window (3 s -> drop), runs held >= 20 s; counter unchanged",
         "source_check": "every recomputed row equals results/real_hand.json variants.held.per_run",
         "per_run_c5": per, "pooled": {}}
  P = out["pooled"]
  for pol in ("C5s1", "C5s3"):
    mine = [r for r in c5 if r["policy"] == pol]
    P[f"{pol}_all"] = pooled(mine, rng)
    for s in ("20 Nov", "24 Nov", "25 Nov"):
      sub = [r for r in mine if r["session"] == s]
      if sub:
        P[f"{pol}_{s.replace(' ', '')}"] = pooled(sub, rng)
  P["C5s3_all_without_24Nov_t13"] = pooled([r for r in c5 if r["policy"] == "C5s3" and (r["session"], r["trial"]) != EXCLUDE], rng)
  P["C5s3_24Nov_without_t13"] = pooled([r for r in c5 if r["policy"] == "C5s3" and r["session"] == "24 Nov" and r["trial"] != EXCLUDE[1]], rng)
  sim = json.loads((E / "results" / "decomposition.json").read_text())["policies"]
  out["sim_K_effort_qturns_per_cycle"] = {p: sim[p]["sim_K_effort"]["qturns_per_cycle"] for p in ("C5s1", "C5s3")}
  out["ratio_real_over_sim"] = {k: v["qturns_per_cycle"] / out["sim_K_effort_qturns_per_cycle"][k[:4]] for k, v in P.items()}
  (E / "results" / "session_sensitivity.json").write_text(json.dumps(out, indent=1) + "\n")

  L = ["# Gait efficiency: seed vs session sensitivity (EXPLORATORY, POST HOC)", "",
       "Generated by `scripts/session_sensitivity.py`. Held window (3 s to the operator's drop time), runs held ≥ 20 s, "
       "counter unchanged; every row equals `results/real_hand.json` (variant `held`). Quarter turns per cycle = operator "
       "quarter turns / encoder cycles. CIs: bootstrap over runs (10,000).", "",
       "## Per run, C5 seeds", "", "| Session | Trial | Policy | Held s | Window s | Quarter turns | Cycles | Quarter turns / cycle | Rhythm Hz |",
       "|---|---|---|---|---|---|---|---|---|"]
  for r in per:
    L.append(f"| {r['session']} | {r['trial']} | {r['policy']} | {r['held_s']:.1f} | {r['window_s']:.1f} | {r['qturns']:g} | "
             f"{r['cycles']:.2f} | {r['qturns_per_cycle']:.2f} | {r['rhythm_hz']:.3f} |")
  L += ["", "## Pooled (ratio of sums)", "", "| Group | Runs | Quarter turns / cycle [95% CI] | Real / sim (K/effort) |", "|---|---|---|---|"]
  for k, v in P.items():
    ci = v["qturns_per_cycle_ci95"]
    L.append(f"| {k} | {v['n_runs']} | {v['qturns_per_cycle']:.2f} [{ci[0]:.2f}, {ci[1]:.2f}] | {out['ratio_real_over_sim'][k]:.3f} |")
  L += ["", "24 Nov trial 13 (C5s3) was held exactly 20 s: 3.09 cycles in a 17-s window at a 0.22 Hz FFT rhythm, against "
        "0.28-0.32 Hz in every other C5s3 run, so the counter undercounts and the run gives 2.27 quarter turns per cycle. "
        "It is kept in the primary analysis (it meets the inclusion rule, held ≥ 20 s) and dropped here only as a sensitivity check."]
  (E / "results" / "session_sensitivity.md").write_text("\n".join(L) + "\n")
  print("\n".join(L))


if __name__ == "__main__":
  main()
