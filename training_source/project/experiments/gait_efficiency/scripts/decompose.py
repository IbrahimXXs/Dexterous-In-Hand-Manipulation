#!/usr/bin/env python3
"""Gait efficiency 2d: sim vs real on finger rhythm and quarter turns per cycle (ANALYSIS_PLAN.md §6-7).

Real: results/real_hand.json, variant "held" (window 3 s -> drop, runs held >= 20 s) = the comparison window;
variant "run" reported next to it.  Sim: results/sim.json, primary setting K/effort (held >= 20 s); the
reference setting A/default is listed for context.  Ratios are real / sim; rules exactly as in the plan.

    python experiments/gait_efficiency/scripts/decompose.py
Writes results/decomposition.json and results/decomposition.md.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

E = Path(__file__).resolve().parents[1]
HAND = ("C5s3", "C5s1", "M400", "A3", "P0", "R1")
BAND = (0.75, 1.25)
STROKE_MIN_RAD, STROKE_REL = 0.2, 0.5


def inside(x: float) -> bool:
  return x is not None and math.isfinite(x) and BAND[0] <= x <= BAND[1]


def ratio(a, b):
  return a / b if (a is not None and b not in (None, 0) and math.isfinite(a) and math.isfinite(b)) else None


def main() -> None:
  real = json.loads((E / "results" / "real_hand.json").read_text())
  sim = json.loads((E / "results" / "sim.json").read_text())
  S, Sref = sim["settings"]["K/effort"], sim["settings"]["A/default"]
  out = {"plan": "ANALYSIS_PLAN.md (sections 6-7)", "band": list(BAND), "policies": {}}
  for p in HAND:
    rh = real["variants"]["held"]["policies"][p]
    rr = real["variants"]["run"]["policies"][p]
    sp = S[p]["primary"]
    row = {"sim_K_effort": {k: sp.get(k) for k in ("n_envs", "qturns_per_cycle", "qturns_per_cycle_ci95", "rhythm_hz_median",
                                                   "cycle_rate_hz", "qturns_per_s", "stroke_amplitude_median_rad")},
           "sim_K_effort_survival_60s": S[p]["survival_60s"], "sim_K_effort_held_ge_20s_share": S[p]["held_ge_20s_share"],
           "sim_A_default": {k: Sref[p]["primary"].get(k) for k in ("n_envs", "qturns_per_cycle", "rhythm_hz_median",
                                                                    "cycle_rate_hz", "qturns_per_s", "stroke_amplitude_median_rad")},
           "real_held": {k: rh.get(k) for k in ("n_runs", "qturns_per_cycle", "qturns_per_cycle_ci95", "rhythm_hz_median",
                                                 "cycle_rate_hz", "qturns_per_s", "stroke_amplitude_median_rad", "qturns_total")},
           "real_run": {k: rr.get(k) for k in ("n_runs", "qturns_per_cycle", "rhythm_hz_median", "cycle_rate_hz",
                                                "stroke_amplitude_median_rad")}}
    row["real_run_r_tpc"] = ratio(rr.get("qturns_per_cycle"), sp.get("qturns_per_cycle"))
    row["real_run_r_rhythm"] = ratio(rr.get("rhythm_hz_median"), sp.get("rhythm_hz_median"))
    if not rh.get("n_runs"):
      row["comparison"] = "no real run held >= 20 s: no primary comparison (descriptive values only)"
      out["policies"][p] = row
      continue
    r_rhythm = ratio(rh["rhythm_hz_median"], sp["rhythm_hz_median"])
    r_rate = ratio(rh["cycle_rate_hz"], sp["cycle_rate_hz"])
    r_tpc = ratio(rh["qturns_per_cycle"], sp["qturns_per_cycle"])
    r_speed = ratio(rh["qturns_per_s"], sp["qturns_per_s"])
    row.update(r_rhythm=r_rhythm, r_rate=r_rate, r_tpc=r_tpc, r_speed=r_speed,
               r_speed_check=(r_rate * r_tpc if (r_rate is not None and r_tpc is not None) else None))
    # rule 1
    if inside(r_rhythm) != inside(r_rate):
      row["rhythm_label"] = "no label: FFT rhythm and cycle rate fall on different sides of a bound"
    else:
      row["rhythm_label"] = "rhythm transferred" if inside(r_rhythm) else "rhythm changed"
    # rule 2
    row["tpc_label"] = "turns per cycle transferred" if inside(r_tpc) else "turns per cycle changed"
    # rule 3
    if rh["qturns_total"] == 0:
      row["speed_label"] = "no rotation on the hand"
    elif inside(r_speed):
      row["speed_label"] = "speed transferred"
    else:
      row["speed_label"] = "speed changed"
      L = math.log(r_speed)
      row["share_rhythm"] = math.log(r_rate) / L
      row["share_tpc"] = math.log(r_tpc) / L
    # rule 4
    a_r, a_s = rh["stroke_amplitude_median_rad"], sp["stroke_amplitude_median_rad"]
    row["stroke_ratio"] = ratio(a_r, a_s)
    row["stroke_label"] = ("finger strokes" if (a_r >= STROKE_MIN_RAD and row["stroke_ratio"] is not None and row["stroke_ratio"] >= STROKE_REL)
                           else "small/twitching motion")
    out["policies"][p] = row
  (E / "results" / "decomposition.json").write_text(json.dumps(out, indent=1) + "\n")
  write_md(out)


def f(x, d=2):
  return "–" if x is None or (isinstance(x, float) and not math.isfinite(x)) else f"{x:.{d}f}"


def write_md(out: dict) -> None:
  L = ["# Gait efficiency: simulation vs real hand (rules of ANALYSIS_PLAN.md §7)", "",
       "Generated by `scripts/decompose.py` from `results/real_hand.json` (variant `held`: window 3 s to the drop, runs held ≥ 20 s; "
       "EXPLORATORY, POST HOC) and `results/sim.json` (setting K, 350 mA-equivalent actuator, environments held ≥ 20 s; pre-registered). "
       "Ratios are real / sim (3 decimals, so values next to a bound are unambiguous); a factor is 'transferred' if the ratio is within 0.75–1.25.", "",
       "| Policy | Real runs | Rhythm Hz, sim → real (ratio) | Cycle rate Hz, sim → real (ratio) | Quarter turns / cycle, sim → real (ratio) | "
       "Quarter turns / held s, sim → real (ratio) | Stroke amplitude rad, sim → real | Labels |", "|---|---|---|---|---|---|---|---|"]
  for p, r in out["policies"].items():
    s, h = r["sim_K_effort"], r["real_held"]
    if "r_tpc" not in r:
      L.append(f"| {p} | 0 | {f(s['rhythm_hz_median'])} → – | {f(s['cycle_rate_hz'])} → – | {f(s['qturns_per_cycle'])} → – | "
               f"{f(s['qturns_per_s'],3)} → – | {f(s['stroke_amplitude_median_rad'])} → – | {r['comparison']} |")
      continue
    labels = [r["rhythm_label"], r["tpc_label"], r["speed_label"], r["stroke_label"]]
    if "share_rhythm" in r:
      labels.append(f"share of the speed change: rhythm {r['share_rhythm']:.0%}, turns per cycle {r['share_tpc']:.0%}")
    L.append(f"| {p} | {h['n_runs']} | {f(s['rhythm_hz_median'])} → {f(h['rhythm_hz_median'])} ({f(r['r_rhythm'],3)}) | "
             f"{f(s['cycle_rate_hz'])} → {f(h['cycle_rate_hz'])} ({f(r['r_rate'],3)}) | "
             f"{f(s['qturns_per_cycle'])} → {f(h['qturns_per_cycle'])} ({f(r['r_tpc'],3)}) | "
             f"{f(s['qturns_per_s'],3)} → {f(h['qturns_per_s'],3)} ({f(r['r_speed'],3)}) | "
             f"{f(s['stroke_amplitude_median_rad'])} → {f(h['stroke_amplitude_median_rad'])} | {'; '.join(labels)} |")
  L += ["", "## Context", "",
        "| Policy | Sim K/effort: 60-s survival; held ≥ 20 s | Sim A/default: q-turns/cycle; rhythm Hz; q-turns / held s | "
        "Real `run` window: q-turns/cycle (ratio to sim K); rhythm Hz (ratio) |", "|---|---|---|---|"]
  for p, r in out["policies"].items():
    a, rr = r["sim_A_default"], r["real_run"]
    L.append(f"| {p} | {f(r['sim_K_effort_survival_60s'],3)}; {f(r['sim_K_effort_held_ge_20s_share'],3)} | "
             f"{f(a['qturns_per_cycle'])}; {f(a['rhythm_hz_median'])}; {f(a['qturns_per_s'],3)} | "
             f"{f(rr.get('qturns_per_cycle'))} ({f(r['real_run_r_tpc'])}); {f(rr.get('rhythm_hz_median'))} ({f(r['real_run_r_rhythm'])}) |")
  (E / "results" / "decomposition.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
  main()
