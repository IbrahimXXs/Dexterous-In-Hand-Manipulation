#!/usr/bin/env python3
"""C5-HW-V2 comparisons (simulation only).

stepb   : FIT_PLAN.md B survival report: frozen C5 seeds and C5-EFFORT from kit starts (K) vs the standard
          grasp-49 start (B), validation seed 7001 -> results/kit_start_survival.{json,md}
decision: PROTOCOL.md decision on the held-out seeds 6201/6202 -> results/v2_comparison.{json,md}

Per-environment arrays come from the saved rollouts (data/items/*.npz here; for the A/B/C settings of the
policies evaluated in C5-HW-EFFORT-V1, its data/*.npz, produced by the identical rollout code, tasks and seeds).
Single-seed exploratory: every CI is a paired bootstrap over evaluation environments (10,000 resamples, the
same indices for all policies; equal seeds give equal reset draws) and describes evaluation variation for one
trained model, not variation between training runs.

    python experiments/c5_hw_v2/scripts/compare_v2.py stepb
    python experiments/c5_hw_v2/scripts/compare_v2.py decision
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

import numpy as np

PROJECT = Path(__file__).resolve().parents[3]
E = PROJECT / "experiments" / "c5_hw_v2"
E1 = PROJECT / "experiments" / "c5_hw_v1"
NBOOT = 10000
C5 = ("C5_1", "C5_2", "C5_3")
A = ("A1", "A2", "A3")
NEW = "C5HW2_1"
EVAL_SEEDS = (6201, 6202)


def _load(name, path):
  spec = importlib.util.spec_from_file_location(name, path)
  mod = importlib.util.module_from_spec(spec)
  sys.modules[name] = mod
  spec.loader.exec_module(mod)
  return mod


V1 = None


def v1():
  global V1
  if V1 is None:
    V1 = _load("c5_hw_v1_eval_items", E1 / "scripts" / "eval_items.py")
  return V1


def per_env(key: str) -> dict | None:
  """Per-environment 30-s turns / failure / survived-30-s and 60-s jam flag of one rollout item."""
  from in_hand_rotation_mjlab.grasp_rotation_v2.rollout import summary_per_env

  for d in (E / "data" / "items", E1 / "data"):
    p = d / f"{key}.npz"
    if p.exists():
      break
  else:
    return None
  tr = dict(np.load(p, allow_pickle=False))
  dt, T = float(tr["dt"]), int(tr["T"])
  s30 = summary_per_env(tr, 600)
  blocked = np.unpackbits(tr["blocked_idx_packed"], axis=0, count=T).astype(bool)
  jam = v1().jam_per_env(blocked, tr["end_step"], dt)
  out = {"turns30": np.asarray(s30["turns"], float), "failure30": np.asarray(s30["failure"], float),
         "survived30": (np.asarray(s30["survival_s"]) >= 600 * dt - 1e-6).astype(float),
         "jam60": np.asarray(jam["jam_60s"] if T >= 1200 else jam["jam_30s"], float), "cache_id": tr["cache_id"]}
  if T >= 1200:
    s60 = summary_per_env(tr, 1200)
    out["turns60"] = np.asarray(s60["turns"], float)
    out["survived60"] = (np.asarray(s60["survival_s"]) >= 1200 * dt - 1e-6).astype(float)
  return out


def key(setting, pol, act, preset, seed, prefix=""):
  return f"{prefix}{setting}_{pol}_{act}_{preset}_s{seed}"


def boot_diff(new: list[np.ndarray], base: list[np.ndarray], rng) -> dict:
  """Paired bootstrap of mean(new - base) pooled over evaluation seeds (resampled within each seed)."""
  diffs = [n - b for n, b in zip(new, base)]
  point = float(np.mean(np.concatenate(diffs)))
  bs = np.empty(NBOOT)
  for i in range(NBOOT):
    bs[i] = np.mean(np.concatenate([d[rng.integers(0, len(d), len(d))] for d in diffs]))
  return {"diff": point, "ci95": [float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))]}


def boot_ratio(new: list[np.ndarray], base: list[np.ndarray], rng) -> dict:
  point = float(np.mean(np.concatenate(new)) / np.mean(np.concatenate(base)))
  bs = np.empty(NBOOT)
  for i in range(NBOOT):
    idx = [rng.integers(0, len(x), len(x)) for x in new]
    bs[i] = np.mean(np.concatenate([x[j] for x, j in zip(new, idx)])) / np.mean(np.concatenate([x[j] for x, j in zip(base, idx)]))
  return {"ratio": point, "ci95": [float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))],
          "frac_boot_below_0.85": float(np.mean(bs < 0.85))}


def mean_of(pols, setting, act, preset, seeds, field, prefix=""):
  """Per seed: per-environment mean over the given policies (the C5 3-seed mean baseline)."""
  out = []
  for s in seeds:
    arrs = [per_env(key(setting, p, act, preset, s, prefix)) for p in pols]
    if any(a is None for a in arrs):
      return None
    out.append(np.mean([a[field] for a in arrs], axis=0))
  return out


def cmd_stepb(a) -> None:
  pols = ("C5_1", "C5_2", "C5_3", "EFFORT_1")
  res = {"seed": 7001, "num_envs": 2048, "steps": 600, "rows": {}}
  rng = np.random.default_rng(20261126)
  L = ["# C5-HW-V2 step B: 30-s survival from kit starts (generated by scripts/compare_v2.py stepb)", "",
       "Validation seed 7001, 2048 environments, 30 s, nominal preset. K = kit-start cache (FIT_PLAN.md B); "
       "B = the standard grasp-49 training start. Survival = still in the first episode at 30 s. "
       "CI: bootstrap over environments (10,000).", "",
       "| policy | actuator | K: survival 30 s [95% CI] | K: turns 30 s | K: jam proxy 30 s | B: survival 30 s | B: turns 30 s | K − B survival [95% CI] |",
       "|---|---|---|---|---|---|---|---|"]
  for p in pols:
    for act in ("default", "effort"):
      kk, kb = per_env(key("K", p, act, "nominal", 7001, "stepB_")), per_env(key("B", p, act, "nominal", 7001, "stepB_"))
      if kk is None or kb is None:
        continue
      sK = kk["survived30"]
      bsK = [np.mean(sK[rng.integers(0, len(sK), len(sK))]) for _ in range(NBOOT)]
      d = boot_diff([kk["survived30"]], [kb["survived30"]], rng)  # same env count, different starts: unpaired in spirit
      row = {"K_survival30": float(sK.mean()), "K_survival30_ci95": [float(np.percentile(bsK, 2.5)), float(np.percentile(bsK, 97.5))],
             "K_turns30": float(kk["turns30"].mean()), "K_jam30": float(kk["jam60"].mean()),
             "B_survival30": float(kb["survived30"].mean()), "B_turns30": float(kb["turns30"].mean()), "K_minus_B_survival": d}
      res["rows"][f"{p}/{act}"] = row
      L.append(f"| {p} | {act} | {row['K_survival30']:.3f} [{row['K_survival30_ci95'][0]:.3f}, {row['K_survival30_ci95'][1]:.3f}] | "
               f"{row['K_turns30']:.3f} | {row['K_jam30']:.4f} | {row['B_survival30']:.3f} | {row['B_turns30']:.3f} | "
               f"{d['diff']:+.3f} [{d['ci95'][0]:+.3f}, {d['ci95'][1]:+.3f}] |")
  c5e = res["rows"].get("C5_1/effort", {}).get("K_survival30")
  efe = res["rows"].get("EFFORT_1/effort", {}).get("K_survival30")
  stop = c5e is not None and efe is not None and c5e < 0.10 and efe < 0.10
  res["stop_rule_B"] = {"rule": "stop if K survival30 < 0.10 for both C5_1 and EFFORT_1 under the effort actuator",
                        "C5_1_effort": c5e, "EFFORT_1_effort": efe, "triggered": bool(stop)}
  L += ["", f"Stop rule B (FIT_PLAN.md): C5_1 {c5e}, EFFORT_1 {efe} under the effort actuator -> "
        f"**{'TRIGGERED: propose a 50/50 mix and ask' if stop else 'not triggered'}**.",
        "", "The K - B CI resamples each start set separately (the two settings use different start states)."]
  (E / "results").mkdir(exist_ok=True)
  (E / "results" / "kit_start_survival.json").write_text(json.dumps(res, indent=1) + "\n")
  (E / "results" / "kit_start_survival.md").write_text("\n".join(L) + "\n")
  print("\n".join(L))


def cmd_decision(a) -> None:
  rng = np.random.default_rng(20261127)
  act = "effort"  # decision actuator (PROTOCOL.md)
  res = {"decision_actuator": act, "eval_seeds": list(EVAL_SEEDS), "criteria": {}}
  # 1. kit-start 30-s survival vs C5 (3-seed mean) and vs C5-EFFORT, setting K
  newK = [per_env(key("K", NEW, act, "nominal", s))["survived30"] for s in EVAL_SEEDS]
  c5K = mean_of(C5, "K", act, "nominal", EVAL_SEEDS, "survived30")
  efK = [per_env(key("K", "EFFORT_1", act, "nominal", s))["survived30"] for s in EVAL_SEEDS]
  d1a, d1b = boot_diff(newK, c5K, rng), boot_diff(newK, efK, rng)
  sn, sc, se = (float(np.mean(np.concatenate(x))) for x in (newK, c5K, efK))
  half = (1 - sn) <= 0.5 * (1 - sc) and (1 - sn) <= 0.5 * (1 - se)
  ok1 = half and all(d["ci95"][0] > 0 for d in (d1a, d1b))
  res["criteria"]["1_kit_start_survival30"] = {"new": sn, "C5_mean": sc, "EFFORT_1": se, "vs_C5": d1a, "vs_EFFORT": d1b,
                                               "failure_new": 1 - sn, "failure_C5_mean": 1 - sc, "failure_EFFORT_1": 1 - se,
                                               "rule": "kit-start 30-s failure (1 - survival) <= 0.5 x C5 mean's and <= 0.5 x C5-EFFORT's, "
                                                       "and both paired-bootstrap 95% CIs of the survival difference have lower bound > 0",
                                               "met": bool(ok1)}
  # 2. jam proxy (60 s), setting A, <= C5-EFFORT
  newJ = [per_env(key("A", NEW, act, "nominal", s))["jam60"] for s in EVAL_SEEDS]
  efJ = [per_env(key("A", "EFFORT_1", act, "nominal", s))["jam60"] for s in EVAL_SEEDS]
  d2 = boot_diff(newJ, efJ, rng)
  ok2 = d2["diff"] <= 0.0
  res["criteria"]["2_jam_proxy_setting_A"] = {"new": float(np.mean(np.concatenate(newJ))), "EFFORT_1": float(np.mean(np.concatenate(efJ))),
                                              "diff": d2, "rule": "new <= EFFORT_1 (point estimate)", "met": bool(ok2)}
  # 3. turns30 on setting A >= 0.85 x C5 (3-seed mean)
  newT = [per_env(key("A", NEW, act, "nominal", s))["turns30"] for s in EVAL_SEEDS]
  c5T = mean_of(C5, "A", act, "nominal", EVAL_SEEDS, "turns30")
  r3 = boot_ratio(newT, c5T, rng)
  ok3 = r3["ratio"] >= 0.85
  res["criteria"]["3_turns30_setting_A"] = {"new": float(np.mean(np.concatenate(newT))), "C5_mean": float(np.mean(np.concatenate(c5T))),
                                            "ratio": r3, "rule": "ratio >= 0.85 (point estimate)", "met": bool(ok3)}
  res["verdict"] = "SINGLE-SEED PASS (exploratory)" if (ok1 and ok2 and ok3) else "FAIL (single-seed exploratory)"
  # descriptive tables: every policy, setting, actuator
  tab = {}
  pols = A + ("R1",) + C5 + ("EFFORT_1", NEW)
  for st in ("A", "B", "C", "K"):
    for ac in ("default", "effort"):
      for p in pols:
        arrs = [per_env(key(st, p, ac, "nominal", s)) for s in EVAL_SEEDS]
        if any(x is None for x in arrs):
          continue
        cat = {f: np.concatenate([x[f] for x in arrs]) for f in ("turns30", "failure30", "survived30", "jam60")}
        tab[f"{st}/{ac}/{p}"] = {f: float(v.mean()) for f, v in cat.items()}
        if all("turns60" in x for x in arrs):
          tab[f"{st}/{ac}/{p}"]["turns60"] = float(np.mean(np.concatenate([x["turns60"] for x in arrs])))
          tab[f"{st}/{ac}/{p}"]["survived60"] = float(np.mean(np.concatenate([x["survived60"] for x in arrs])))
  for preset in ("heavy_slippery", "high_delay", "obs_noise_x3"):
    for ac in ("default", "effort"):
      for p in pols:
        x = per_env(key("A", p, ac, preset, 6201))
        if x is not None:
          tab[f"A-{preset}-6201/{ac}/{p}"] = {f: float(x[f].mean()) for f in ("turns30", "failure30", "survived30", "jam60")}
  res["table"] = tab
  (E / "results" / "v2_comparison.json").write_text(json.dumps(res, indent=1) + "\n")
  L = ["# C5-HW-V2: held-out comparison and pre-registered decision (generated by scripts/compare_v2.py decision)", "",
       "**Single-seed exploratory.** CIs are paired bootstraps over evaluation environments (10,000), seeds 6201 + 6202 pooled; "
       "they describe evaluation variation for this one trained model, not variation between training runs.", "",
       f"Decision actuator: **{act}** (350 mA-equivalent). Verdict: **{res['verdict']}**", "",
       "| criterion | value | rule | met |", "|---|---|---|---|"]
  c = res["criteria"]
  L.append(f"| 1 kit-start survival 30 s | new {c['1_kit_start_survival30']['new']:.3f}; C5 mean {c['1_kit_start_survival30']['C5_mean']:.3f} "
           f"(diff {d1a['diff']:+.3f} [{d1a['ci95'][0]:+.3f}, {d1a['ci95'][1]:+.3f}]); C5-EFFORT {c['1_kit_start_survival30']['EFFORT_1']:.3f} "
           f"(diff {d1b['diff']:+.3f} [{d1b['ci95'][0]:+.3f}, {d1b['ci95'][1]:+.3f}]) | failure <= 0.5 x each baseline's and both CIs > 0 | {'yes' if ok1 else 'NO'} |")
  L.append(f"| 2 jam proxy 60 s, setting A | new {c['2_jam_proxy_setting_A']['new']:.4f}; C5-EFFORT {c['2_jam_proxy_setting_A']['EFFORT_1']:.4f} "
           f"(diff {d2['diff']:+.4f} [{d2['ci95'][0]:+.4f}, {d2['ci95'][1]:+.4f}]) | new <= C5-EFFORT | {'yes' if ok2 else 'NO'} |")
  L.append(f"| 3 turns 30 s, setting A | new {c['3_turns30_setting_A']['new']:.3f}; C5 mean {c['3_turns30_setting_A']['C5_mean']:.3f}; "
           f"ratio {r3['ratio']:.3f} [{r3['ci95'][0]:.3f}, {r3['ci95'][1]:.3f}] | ratio >= 0.85 | {'yes' if ok3 else 'NO'} |")
  L += ["", "## All policies (seeds 6201 + 6202 pooled, nominal; presets: setting A, seed 6201)", "",
        "| setting / actuator / policy | turns 30 s | failure 30 s | survived 30 s | jam proxy | turns 60 s | survived 60 s |",
        "|---|---|---|---|---|---|---|"]
  for k, v in tab.items():
    L.append(f"| {k} | {v['turns30']:.3f} | {v['failure30']:.3f} | {v['survived30']:.3f} | {v['jam60']:.4f} | "
             f"{v.get('turns60', float('nan')):.3f} | {v.get('survived60', float('nan')):.3f} |")
  (E / "results" / "v2_comparison.md").write_text("\n".join(L) + "\n")
  print("\n".join(L[:12]))


def main():
  ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
  ap.add_argument("cmd", choices=("stepb", "decision"))
  a = ap.parse_args()
  {"stepb": cmd_stepb, "decision": cmd_decision}[a.cmd](a)


if __name__ == "__main__":
  main()
